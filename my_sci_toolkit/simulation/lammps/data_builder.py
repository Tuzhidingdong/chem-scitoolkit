"""LAMMPS data format writer from atomic coordinates and simulation boxes."""

from pathlib import Path
from typing import List, Tuple, Dict, Optional


def write_lammps_data(
    output_path: str | Path,
    box_bounds: Tuple[float, float, float, float, float, float],  # xlo, xhi, ylo, yhi, zlo, zhi
    atoms: List[Tuple[int, int, float, float, float, float]],     # (atom_id, type_id, charge, x, y, z)
    masses: Dict[int, float],                                     # type_id -> mass
    title: str = "LAMMPS data file generated by my_sci_toolkit",
) -> Path:
    """Construct a clean, standard full-format LAMMPS *.data file."""
    out_p = Path(output_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)

    xlo, xhi, ylo, yhi, zlo, zhi = box_bounds
    n_atoms = len(atoms)
    n_types = len(masses)

    lines = [
        title,
        "",
        f"    {n_atoms} atoms",
        f"    {n_types} atom types",
        "",
        f"    {xlo:.6f} {xhi:.6f} xlo xhi",
        f"    {ylo:.6f} {yhi:.6f} ylo yhi",
        f"    {zlo:.6f} {zhi:.6f} zlo zhi",
        "",
        "Masses",
        "",
    ]

    for type_id, mass in sorted(masses.items()):
        lines.append(f"    {type_id} {mass:.4f}")

    lines.append("")
    lines.append("Atoms # full style (id type charge x y z)")
    lines.append("")

    for atom_id, type_id, q, x, y, z in atoms:
        lines.append(f"    {atom_id} 1 {type_id} {q:.4f} {x:.6f} {y:.6f} {z:.6f}")

    with open(out_p, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    return out_p
